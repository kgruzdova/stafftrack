const base=process.env.TEST_URL||'http://127.0.0.1:5173', stamp=crypto.randomUUID();
const password='Test-'+crypto.randomUUID();
function client(){let cookie='';return async(path,method='GET',body,expected=200)=>{
 const r=await fetch(`${base}/api/${path}`,{method,headers:{cookie,'Content-Type':'application/json'},...(body?{body:JSON.stringify(body)}:{})});
 if(r.headers.get('set-cookie'))cookie=r.headers.get('set-cookie').split(';')[0];
 const data=await r.json();assert.equal(r.status,expected,`${method} ${path}: ${JSON.stringify(data)}`);return data;
}}
